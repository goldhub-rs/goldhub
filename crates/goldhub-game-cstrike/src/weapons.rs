/// Weapon classification slot in the player's inventory.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[cfg_attr(feature = "serde", derive(Serialize, Deserialize))]
pub enum WeaponSlot {
    Primary = 1,
    Secondary = 2,
    Melee = 3,
    Grenade = 4,
    C4 = 5,
}

impl WeaponId {
    /// Returns the inventory slot for this weapon.
    #[must_use]
    pub const fn slot(self) -> WeaponSlot {
        match self {
            Self::Knife => WeaponSlot::Melee,
            Self::P228
            | Self::Glock
            | Self::Elite
            | Self::FiveSeven
            | Self::USP45
            | Self::Glock18
            | Self::Deagle => WeaponSlot::Secondary,
            Self::HeGrenade | Self::SmokeGrenade | Self::Flashbang => WeaponSlot::Grenade,
            Self::C4 => WeaponSlot::C4,
            Self::Scout
            | Self::XM1014
            | Self::Mac10
            | Self::Aug
            | Self::Ump45
            | Self::Sg550
            | Self::Galil
            | Self::Famas
            | Self::AWP
            | Self::Mp5
            | Self::M249
            | Self::M3
            | Self::M4A1
            | Self::Tmp
            | Self::G3SG1
            | Self::Sg552
            | Self::AK47
            | Self::P90 => WeaponSlot::Primary,
        }
    }

    /// Returns an array of all 30 canonical weapons.
    #[must_use]
    pub const fn all() -> [Self; 30] {
        [
            Self::P228,
            Self::Glock,
            Self::Scout,
            Self::HeGrenade,
            Self::XM1014,
            Self::C4,
            Self::Mac10,
            Self::Aug,
            Self::SmokeGrenade,
            Self::Elite,
            Self::FiveSeven,
            Self::Ump45,
            Self::Sg550,
            Self::Galil,
            Self::Famas,
            Self::USP45,
            Self::Glock18,
            Self::AWP,
            Self::Mp5,
            Self::M249,
            Self::M3,
            Self::M4A1,
            Self::Tmp,
            Self::G3SG1,
            Self::Flashbang,
            Self::Deagle,
            Self::Sg552,
            Self::AK47,
            Self::Knife,
            Self::P90,
        ]
    }
}

